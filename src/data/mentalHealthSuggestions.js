export const MENTAL_HEALTH_SUGGESTIONS = [
  ...SAD, ...ANXIOUS, ...STRESSED, ...LONELY, ...ANGRY, ...OK
];

export function getSuggestionsByCategory(category, limit) {
  if (!category) return MENTAL_HEALTH_SUGGESTIONS;
  const list = MENTAL_HEALTH_SUGGESTIONS.filter((s) => s.category === category);
  return typeof limit === "number" ? list.slice(0, limit) : list;
}

export function getSuggestionStats() {
  const out = {};
  for (const s of MENTAL_HEALTH_SUGGESTIONS) {
    out[s.category] = (out[s.category] || 0) + 1;
  }
  return { total: MENTAL_HEALTH_SUGGESTIONS.length, byCategory: out };
}
